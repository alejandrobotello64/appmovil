/** Traduce chrome UI. Si no hay entrada, deja el texto (p. ej. datos de negocio). */
export function chromeLabel(locale: Locale, text: string): string {
  if (!text || locale === "es") return text;
  const direct = CHROME_EN[text];
  if (direct) return direct;
  const trimmed = text.trim();
  if (trimmed !== text) {
    const hit = CHROME_EN[trimmed];
    if (hit) return text.replace(trimmed, hit);
  }
  return text;
}
