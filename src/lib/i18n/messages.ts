export const messages: Record<Locale, Dict> = { es, en };

export function isLocale(value: unknown): value is Locale {
  return value === "es" || value === "en";
}

export function translate(
  locale: Locale,
  key: string,
  fallback?: string
): string {
  return messages[locale][key] ?? messages.es[key] ?? fallback ?? key;
}

/** Locale guardado en el navegador (para PDFs / reportes fuera de React). */
export function getStoredLocale(): Locale {
  if (typeof window === "undefined") return "es";
  try {
    const stored = localStorage.getItem(LOCALE_STORAGE_KEY);
    return isLocale(stored) ? stored : "es";
  } catch {
    return "es";
  }
}

export function localeTag(locale: Locale = getStoredLocale()): string {
  return locale === "en" ? "en-US" : "es-MX";
}
