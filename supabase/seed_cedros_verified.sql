  quantity,
  min_stock,
  unit,
  location,
  brand,
  color_tag,
  model,
  serial_number,
  unit_price,
  supplier,
  notes,
  is_active,
  part_number,
  manufacturer,
  subcategory
)
select
  f.sku_prefix || '-' || lpad((coalesce(seq.max_seq, 0) + f.rn)::text, 6, '0'),
  f.name,
  f.category,
  case when f.category = 'equipos' then 'equipo' else 'producto' end,
  f.description,
  0,
  0,
  f.unit,
  '',
  f.brand,
  'rojo',
  '',
  '',
  0,
  '',
  f.notes,
  true,
  f.part_number,
  f.brand,
  ''
from fresh f
left join seq on seq.prefix = f.sku_prefix;

